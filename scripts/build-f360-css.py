#!/usr/bin/env python3
"""Rebuild field360/src/f360.css and chakra.css from FieldShift360's originals, recoloured to KormoPath.

Usage: python3 -I scripts/build-f360-css.py <fieldshift360 index.css> [<chakra.css source>]

Same method as app/globals.css: every colour keeps its OKLCH lightness (so text contrast stays as FieldShift360
designed it) and only hue/chroma move onto the Shonar Bangla palette:
  paddy green -> Padma green (h 163) · river teal -> river blue (h 253) · sunrise gold -> haldi (h 72)
  Barind laterite -> terracotta (h 41) · green-grey neutrals -> warm earth (h 62, low chroma)
Whites, blacks, reds, violets and other accents are left as they are.
"""
import math, re, sys
from pathlib import Path

def srgb_to_lin(c):
    c /= 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4

def lin_to_srgb(c):
    c = max(0.0, min(1.0, c))
    v = 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055
    return round(max(0, min(1, v)) * 255)

def to_oklch(r, g, b):
    r, g, b = srgb_to_lin(r), srgb_to_lin(g), srgb_to_lin(b)
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l, m, s = l ** (1 / 3), m ** (1 / 3), s ** (1 / 3)
    L = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s
    A = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s
    B = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s
    return L, math.hypot(A, B), math.degrees(math.atan2(B, A)) % 360

def from_oklch(L, C, H):
    A, B = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3
    m = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3
    s = (L - 0.0894841775 * A - 1.2914855480 * B) ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    b = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return lin_to_srgb(r), lin_to_srgb(g), lin_to_srgb(b)

def fits(L, C, H):
    r, g, b = from_oklch(L, C, H)
    L2, C2, _ = to_oklch(r, g, b)
    return abs(L2 - L) < 0.02 and abs(C2 - C) < 0.02

def remap(r, g, b):
    L, C, H = to_oklch(r, g, b)
    if C < 0.012:
        return None                         # white, black, greys: unchanged
    if 95 <= H < 180 and C < 0.05:
        H2, C2 = 62, min(C, 0.025)          # green-grey neutrals -> warm earth
    elif 95 <= H < 180:
        H2, C2 = 163, C                     # paddy green -> Padma green
    elif 180 <= H < 215:
        H2, C2 = 253, C                     # river teal -> river blue
    elif 60 <= H < 95:
        H2, C2 = 72, C                      # sunrise gold -> haldi
    elif 25 <= H < 60:
        H2, C2 = 41, C                      # laterite -> terracotta
    else:
        return None
    while C2 > 0.005 and not fits(L, C2, H2):
        C2 *= 0.92                          # pull chroma in until the colour is inside sRGB
    return from_oklch(L, C2, H2)

def hexsub(m):
    h = m.group(0)[1:]
    out = remap(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))
    return m.group(0) if out is None else '#%02x%02x%02x' % out

def rgbsub(m):
    r, g, b = int(m.group(2)), int(m.group(3)), int(m.group(4))
    out = remap(r, g, b)
    return m.group(0) if out is None else f'{m.group(1)}({out[0]}, {out[1]}, {out[2]}'

def recolour(css):
    css = re.sub(r'#[0-9a-fA-F]{6}\b', hexsub, css)
    return re.sub(r'(rgba?)\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)', rgbsub, css)

HEADER = """/* GENERATED by scripts/build-f360-css.py from FieldShift360 (MIT, razibr246/fieldshift360) src/index.css.
   Loaded only on /krishi/field. Its own Tailwind build scans field360/src only, so it never reaches other apps.
   Colours are recoloured to KormoPath's Shonar Bangla palette (see the script). Do not edit by hand. */
"""

def main():
    src = Path(sys.argv[1]).read_text()
    css = recolour(src)
    css = css.replace('@import "tailwindcss";', '@import "tailwindcss" source(none);\n@source "./";', 1)
    # KormoPath surfaces and type on top of the recoloured FieldShift360 tokens.
    css = re.sub(r'--color-ink: #[0-9a-f]{6};', '--color-ink: #22180f;', css, count=1)
    css = re.sub(r'--color-canvas: #[0-9a-f]{6};', '--color-canvas: #fcf9f3;', css, count=1)
    css = re.sub(r'--color-border: #[0-9a-f]{6};', '--color-border: #eadfce;', css, count=1)
    css = re.sub(r'--color-soft: #[0-9a-f]{6};', '--color-soft: #f6eee2;', css, count=1)
    css = css.replace('background: #f5f7f2;', 'background: #fcf9f3;', 1)
    css += """
/* KormoPath headings: Fraunces + Noto Serif Bengali (next/font variables from app/layout.tsx). */
h1, h2, .font-display { font-family: var(--font-fraunces), var(--font-bn-serif), Georgia, "Noto Sans Bengali Variable", serif; font-optical-sizing: auto; }
"""
    out = Path(__file__).resolve().parent.parent / 'field360/src/f360.css'
    out.write_text(HEADER + css)
    print('wrote', out)
    if len(sys.argv) > 2:
        c = Path(__file__).resolve().parent.parent / 'field360/src/components/chakra/chakra.css'
        c.write_text(recolour(Path(sys.argv[2]).read_text()))
        print('recoloured', c)

if __name__ == '__main__':
    main()
